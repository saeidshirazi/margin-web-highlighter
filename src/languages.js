export function languageCode(value, allowAuto = false) {
  const code = String(value || '').trim();
  if (allowAuto && code === 'auto') return code;
  if (!/^[a-z]{2,3}(?:-[a-zA-Z0-9]{2,8}){0,3}$/.test(code))
    throw new Error('Enter a valid language code, such as fa, en, or zh-Hant.');
  try {
    return new Intl.Locale(code).toString();
  } catch {
    throw new Error('Invalid language code.');
  }
}
